// Genesis machine: an original General MIDI bank of 4-operator FM patches for the YM2612, written from
// scratch in register terms for RetroSynths (not derived from any game, driver or commercial bank).
//
// A patch: [alg, fb, op1, op2, op3, op4, extras]
//   op = [MUL, TL, AR, D1R, D2R, SL, RR, DT, KS, AM, SSG]  (register values; DT 0..7 with 4..7 negative,
//        KS = rate scaling 0..3, AM = 1 to follow the LFO, SSG = 0 or 8..15). Operators in OP1..OP4 order
//        (register offsets +0, +8, +4, +12). Carrier TLs are written relative: the driver adds the
//        velocity / volume attenuation to the carriers of the algorithm.
//   extras: { tr: transpose (semitones), ams, pms (LFO sensitivity, 0..3 / 0..7), lvl: level trim in dB,
//             psg: [attack s, decay s, sustain 0..1, release s] envelope used when the PSG takes the note,
//             fixed: MIDI note to play regardless of key (FX) }

const P = (alg, fb, o1, o2, o3, o4, x = {}) => ({ alg, fb, op: [o1, o2, o3, o4].map(op), ...x });
function op(a) {
  const [mul, tl, ar, d1r, d2r, sl, rr, dt = 0, ks = 0, am = 0, ssg = 0] = a;
  return { mul, tl, ar, d1r, d2r, sl, rr, dt, ks, am, ssg };
}
